[CmdletBinding()]
param(
    [string]$ProjectRoot = "D:\OneDrive\Desktop\ARABIA STRIKE WORLD WAR\arabiastrike.worldwar",
    [string]$UERoot = "D:\UE_5.8"
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

function Stop-Gate([string]$Reason, [int]$Code = 1) {
    Write-Host ""
    Write-Host "JEDDAH_REPAIR_RESUME=STOPPED" -ForegroundColor Red
    Write-Host "BLOCKER=$Reason" -ForegroundColor Red
    Write-Host "DO_NOT_DELETE_OR_REGENERATE_UMAP" -ForegroundColor Yellow
    Write-Host "DO_NOT_COMMIT_DO_NOT_PULL_DO_NOT_RESET_DO_NOT_RESTORE" -ForegroundColor Yellow
    Write-Host "DO_NOT_TOUCH_MAIN" -ForegroundColor Red
    exit $Code
}

Set-Location $ProjectRoot

$Branch = (& git branch --show-current).Trim()
Write-Host "BRANCH=$Branch" -ForegroundColor Cyan
if ($Branch -ne "codex/asww-development") {
    Stop-Gate "WRONG_BRANCH_$Branch" 10
}

$Project = Join-Path $ProjectRoot "ArabiaStrikeWorldWar.uproject"
$Map = Join-Path $ProjectRoot "Content\Maps\Jeddah_RedSea_Assault.umap"
$Editor = Join-Path $UERoot "Engine\Binaries\Win64\UnrealEditor-Cmd.exe"
$EvidenceRoot = Join-Path $ProjectRoot "Saved\RuntimeEvidence\JeddahMap"

foreach ($Required in @($Project,$Map,$Editor,$EvidenceRoot)) {
    if (-not (Test-Path -LiteralPath $Required)) {
        Stop-Gate "MISSING_$Required" 11
    }
}

$RunningEditors = @(Get-Process UnrealEditor,UnrealEditor-Cmd -ErrorAction SilentlyContinue)
if ($RunningEditors.Count -gt 0) {
    $RunningEditors | Select-Object Id,ProcessName,StartTime | Format-Table -AutoSize
    Stop-Gate "CLOSE_ALL_UNREAL_EDITOR_PROCESSES_FIRST" 12
}

# Confirm map package header before any mutation.
$Stream = [IO.File]::OpenRead($Map)
try {
    $Reader = [IO.BinaryReader]::new($Stream)
    try { $Magic = $Reader.ReadUInt32() }
    finally { $Reader.Dispose() }
}
finally { $Stream.Dispose() }

$Expected = [Convert]::ToUInt32("9E2A83C1",16)
Write-Host ("MAP_MAGIC=0x{0:X8}" -f $Magic)
if ($Magic -ne $Expected) {
    Stop-Gate "INVALID_UNREAL_PACKAGE_HEADER" 13
}
Write-Host "REAL_UNREAL_PACKAGE_HEADER=True" -ForegroundColor Green

# Locate scripts that were already generated by the previous smart-repair run.
$RepairPy = Get-ChildItem -LiteralPath $EvidenceRoot -File -Filter "repair_jeddah_content_*.py" -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending |
    Select-Object -First 1

$ValidatePy = Get-ChildItem -LiteralPath $EvidenceRoot -File -Filter "validate_jeddah_after_content_repair_*.py" -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending |
    Select-Object -First 1

if (-not $RepairPy) {
    Stop-Gate "REPAIR_PY_NOT_FOUND" 20
}
if (-not $ValidatePy) {
    Stop-Gate "VALIDATE_PY_NOT_FOUND" 21
}

# This is the key fix: Unreal receives forward-slash paths.
# The previous failure showed '\r' in '\repair...' being interpreted as a control character.
$ProjectForUE = $Project.Replace('\','/')
$RepairForUE = $RepairPy.FullName.Replace('\','/')
$ValidateForUE = $ValidatePy.FullName.Replace('\','/')

Write-Host ""
Write-Host "REPAIR_PY=$($RepairPy.FullName)" -ForegroundColor Cyan
Write-Host "REPAIR_PY_FOR_UE=$RepairForUE" -ForegroundColor Green
Write-Host "VALIDATE_PY=$($ValidatePy.FullName)" -ForegroundColor Cyan
Write-Host "VALIDATE_PY_FOR_UE=$ValidateForUE" -ForegroundColor Green

# Fresh safety backup before actually executing the repair.
$Stamp = Get-Date -Format "yyyyMMdd_HHmmss"
$BackupRoot = Join-Path $ProjectRoot "Saved\Verification\FixBackups\Jeddah_BeforeForwardSlashRepair_$Stamp"
New-Item -ItemType Directory -Force -Path $BackupRoot | Out-Null
Copy-Item -LiteralPath $Map -Destination (Join-Path $BackupRoot "Jeddah_RedSea_Assault.umap") -Force

$ExternalPaths = @(
    (Join-Path $ProjectRoot "Content\__ExternalActors__\Maps\Jeddah_RedSea_Assault"),
    (Join-Path $ProjectRoot "Content\__ExternalObjects__\Maps\Jeddah_RedSea_Assault")
)
foreach ($Path in $ExternalPaths) {
    if (Test-Path -LiteralPath $Path -PathType Container) {
        $ParentName = Split-Path (Split-Path $Path -Parent) -Leaf
        $Leaf = Split-Path $Path -Leaf
        $Dest = Join-Path $BackupRoot "$ParentName\$Leaf"
        New-Item -ItemType Directory -Force -Path (Split-Path $Dest -Parent) | Out-Null
        Copy-Item -LiteralPath $Path -Destination $Dest -Recurse -Force
    }
}
Write-Host "BACKUP=$BackupRoot" -ForegroundColor Green

$RepairLog = Join-Path $EvidenceRoot "repair_forwardslash_$Stamp.log"
$ValidateLog = Join-Path $EvidenceRoot "validate_after_forwardslash_repair_$Stamp.log"

Write-Host ""
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host " JEDDAH CONTENT REPAIR — FORWARD-SLASH EXECUTION" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan

$RepairArgs = @(
    $ProjectForUE,
    "-ExecutePythonScript=$RepairForUE",
    "-Unattended",
    "-NoSplash",
    "-NoSound",
    "-NullRHI",
    "-NoSourceControl",
    "-stdout",
    "-FullStdOutLogOutput"
)

& $Editor @RepairArgs 2>&1 | Tee-Object -FilePath $RepairLog
$RepairExit = $LASTEXITCODE
$RepairPass = Select-String -LiteralPath $RepairLog -SimpleMatch "ASWW_CONTENT_REPAIR_RESULT=PASS" -Quiet

Write-Host ""
Write-Host "REPAIR_EXIT=$RepairExit"
Write-Host "REPAIR_MARKER=$RepairPass"
Write-Host "REPAIR_LOG=$RepairLog"

if ($RepairExit -ne 0 -or -not $RepairPass) {
    Write-Host ""
    Write-Host "=== REPAIR ROOT CAUSE ===" -ForegroundColor Yellow
    Select-String -LiteralPath $RepairLog `
        -Pattern "Could not load Python file|LogPython:\s*Error|Traceback|RuntimeError:|AttributeError:|TypeError:|Failed to spawn actor|Project class failed to load|Failed to save repaired Jeddah level|ASWW_REPAIR_" `
        -Context 4,14 |
        Select-Object -First 80
    Stop-Gate "CONTENT_REPAIR_FAILED_AFTER_FORWARD_SLASH_FIX" 30
}

Write-Host "CONTENT_REPAIR=PASS" -ForegroundColor Green

Write-Host ""
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host " FRESH JEDDAH VALIDATION — NEW UNREAL PROCESS" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan

$ValidateArgs = @(
    $ProjectForUE,
    "-ExecutePythonScript=$ValidateForUE",
    "-Unattended",
    "-NoSplash",
    "-NoSound",
    "-NullRHI",
    "-NoSourceControl",
    "-stdout",
    "-FullStdOutLogOutput"
)

& $Editor @ValidateArgs 2>&1 | Tee-Object -FilePath $ValidateLog
$ValidateExit = $LASTEXITCODE

$WP = Select-String -LiteralPath $ValidateLog -SimpleMatch "ASWW_WORLD_PARTITION=PASS" -Quiet
$MapPass = Select-String -LiteralPath $ValidateLog -SimpleMatch "ASWW_MAP_LOAD_RESULT=PASS" -Quiet
$Missing = Select-String -LiteralPath $ValidateLog -SimpleMatch "ASWW_MISSING_ACTORS=" | Select-Object -Last 1

Write-Host ""
Write-Host "VALIDATION_EXIT=$ValidateExit"
Write-Host "WORLD_PARTITION_MARKER=$WP"
Write-Host "MAP_LOAD_MARKER=$MapPass"
if ($Missing) { Write-Host $Missing.Line }
Write-Host "VALIDATION_LOG=$ValidateLog"

if ($ValidateExit -eq 0 -and $WP -and $MapPass) {
    Write-Host ""
    Write-Host "JEDDAH_CONTENT_VALIDATION=PASS" -ForegroundColor Green
    Write-Host "NEXT_GATE=PATCH_REPO_VALIDATOR_AND_PROMOTE_DEFAULT_MAP" -ForegroundColor Green
    Write-Host "DO_NOT_COMMIT_YET" -ForegroundColor Yellow
    exit 0
}

Write-Host ""
Write-Host "=== FRESH VALIDATION ROOT CAUSE ===" -ForegroundColor Yellow
Select-String -LiteralPath $ValidateLog `
    -Pattern "Could not load Python file|LogPython:\s*Error|Traceback|RuntimeError:|AttributeError:|TypeError:|ASWW_MISSING_ACTORS=|PlayerStart|ASGameMode|World Partition|failed to load" `
    -Context 4,14 |
    Select-Object -First 80

Stop-Gate "FRESH_VALIDATION_FAILED_AFTER_REPAIR" 40
